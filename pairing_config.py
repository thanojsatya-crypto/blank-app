"""OS-CSPRNG pairing-password generation for the volatile classroom demo."""
from __future__ import annotations

import re
import secrets

PAIRING_PASSWORD_BYTES = 24
PAIRING_PASSWORD_PATTERN = re.compile(r"[A-Za-z0-9_-]{32}\Z", re.ASCII)


def generate_pairing_password() -> str:
    """Generate a fresh 192-bit URL-safe pairing password using the OS CSPRNG."""
    password = secrets.token_urlsafe(PAIRING_PASSWORD_BYTES)
    if not PAIRING_PASSWORD_PATTERN.fullmatch(password):
        raise RuntimeError("The operating system did not return a valid pairing password.")
    return password


def validate_pairing_password(password: object) -> bool:
    """Accept only the fixed-length URL-safe value generated by this app."""
    return isinstance(password, str) and PAIRING_PASSWORD_PATTERN.fullmatch(password) is not None
